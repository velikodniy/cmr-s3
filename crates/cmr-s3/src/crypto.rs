use std::{fs::OpenOptions, io::Write, path::Path};

use aes_gcm::{
    Aes256Gcm,
    aead::{AeadInOut, KeyInit},
};
use aes_kw::KwAes256;
use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD};
use bytes::Bytes;
use hkdf::Hkdf;
use hmac::{Hmac, Mac};
use serde::{Deserialize, Serialize};
use sha2::Sha256;
use zeroize::{Zeroize, Zeroizing};

use crate::{Error, Result};

const KEY_BYTES: usize = 32;
const JWK_KEY_TYPE: &str = "oct";
const HKDF_SALT: &[u8] = b"cmr-s3 format 1";
const HKDF_WRAPPING_INFO: &[u8] = b"key wrapping";
const HKDF_NAMING_INFO: &[u8] = b"record names";
const MAGIC: &[u8; 8] = b"CMRS3\0\0\x01";
const NONCE_BYTES: usize = 12;
const KEY_WRAP_OVERHEAD: usize = 8;
const WRAPPED_KEY_BYTES: usize = KEY_BYTES + KEY_WRAP_OVERHEAD;
const TAG_BYTES: usize = 16;
// The nonce is zero because every record gets a fresh, single-use data key.
const NONCE: [u8; NONCE_BYTES] = [0; NONCE_BYTES];
const HEADER: usize = MAGIC.len() + WRAPPED_KEY_BYTES;
pub(crate) const OVERHEAD: usize = HEADER + TAG_BYTES;

#[derive(Serialize, Deserialize)]
struct KeyJwk {
    kty: String,
    k: String,
}

impl Drop for KeyJwk {
    fn drop(&mut self) {
        self.k.zeroize();
    }
}

/// The master secret required to recover encrypted cloud storage.
pub struct EncryptionKey(Zeroizing<[u8; KEY_BYTES]>);

impl EncryptionKey {
    /// Construct a key from 32 securely generated bytes.
    pub fn from_bytes(bytes: [u8; 32]) -> Self {
        Self(Zeroizing::new(bytes))
    }

    /// Read a private RFC 7517 symmetric JWK containing a 256-bit key.
    pub fn read(path: impl AsRef<Path>) -> Result<Self> {
        let mut file = std::fs::File::open(path)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            if file.metadata()?.permissions().mode() & 0o077 != 0 {
                return Err(Error::Configuration(
                    "the encryption key file must be private to its owner".into(),
                ));
            }
        }
        let invalid_jwk = || {
            Error::Configuration(
                "the encryption key file must be an oct JWK with an unpadded base64url 256-bit key"
                    .into(),
            )
        };
        let mut json = Zeroizing::new(Vec::new());
        std::io::Read::read_to_end(&mut file, &mut json)?;
        let jwk: KeyJwk = serde_json::from_slice(&json).map_err(|_| invalid_jwk())?;
        if jwk.kty != JWK_KEY_TYPE {
            return Err(invalid_jwk());
        }
        let mut bytes = Zeroizing::new([0; KEY_BYTES]);
        let length = URL_SAFE_NO_PAD
            .decode_slice(&jwk.k, bytes.as_mut())
            .map_err(|_| invalid_jwk())?;
        if length != KEY_BYTES {
            return Err(invalid_jwk());
        }
        Ok(Self(bytes))
    }

    /// Create and synchronize a new private key file without replacing an existing file.
    pub fn generate(path: impl AsRef<Path>) -> Result<()> {
        let mut bytes = Zeroizing::new([0; KEY_BYTES]);
        getrandom::fill(bytes.as_mut()).map_err(|_| Error::Random)?;
        let jwk = KeyJwk {
            kty: JWK_KEY_TYPE.into(),
            k: URL_SAFE_NO_PAD.encode(bytes.as_ref()),
        };
        let json = Zeroizing::new(serde_json::to_vec(&jwk)?);
        let mut options = OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        let mut file = options.open(path.as_ref())?;
        file.write_all(&json)?;
        file.sync_all()?;
        if let Some(parent) = path
            .as_ref()
            .parent()
            .filter(|path| !path.as_os_str().is_empty())
        {
            std::fs::File::open(parent)?.sync_all()?;
        }
        Ok(())
    }
}

pub(crate) struct Cipher {
    wrapping: Zeroizing<[u8; KEY_BYTES]>,
    naming: Zeroizing<[u8; KEY_BYTES]>,
}

impl Cipher {
    pub fn new(key: EncryptionKey) -> Self {
        let hkdf = Hkdf::<Sha256>::new(Some(HKDF_SALT), key.0.as_ref());
        let mut wrapping = Zeroizing::new([0; KEY_BYTES]);
        let mut naming = Zeroizing::new([0; KEY_BYTES]);
        hkdf.expand(HKDF_WRAPPING_INFO, wrapping.as_mut())
            .expect("valid HKDF output length");
        hkdf.expand(HKDF_NAMING_INFO, naming.as_mut())
            .expect("valid HKDF output length");
        Self { wrapping, naming }
    }

    pub fn name(&self, fields: &[&str]) -> String {
        let mut mac = <Hmac<Sha256> as hmac::KeyInit>::new_from_slice(self.naming.as_ref())
            .expect("valid HMAC key length");
        for field in fields {
            mac.update(&(field.len() as u64).to_be_bytes());
            mac.update(field.as_bytes());
        }
        hex::encode(mac.finalize().into_bytes())
    }

    pub fn seal(&self, context: &str, mut buffer: Vec<u8>) -> Result<Vec<u8>> {
        let mut key = Zeroizing::new([0; KEY_BYTES]);
        getrandom::fill(key.as_mut()).map_err(|_| Error::Random)?;
        let wrapper =
            KwAes256::new_from_slice(self.wrapping.as_ref()).map_err(|_| Error::Encryption)?;
        let mut wrapped = [0; WRAPPED_KEY_BYTES];
        wrapper
            .wrap_key(key.as_ref(), &mut wrapped)
            .map_err(|_| Error::Encryption)?;
        let cipher = Aes256Gcm::new_from_slice(key.as_ref()).map_err(|_| Error::Encryption)?;
        let mut aad = Vec::with_capacity(MAGIC.len() + context.len());
        aad.extend_from_slice(MAGIC);
        aad.extend_from_slice(context.as_bytes());
        let size = buffer.len();
        buffer.reserve(OVERHEAD);
        buffer.resize(size + HEADER, 0);
        buffer.copy_within(..size, HEADER);
        buffer[..MAGIC.len()].copy_from_slice(MAGIC);
        buffer[MAGIC.len()..HEADER].copy_from_slice(&wrapped);
        let tag = cipher
            .encrypt_inout_detached(&NONCE.into(), &aad, (&mut buffer[HEADER..]).into())
            .map_err(|_| Error::Encryption)?;
        buffer.extend_from_slice(&tag);
        Ok(buffer)
    }

    pub fn open(&self, context: &str, mut ciphertext: Vec<u8>) -> Result<Bytes> {
        if ciphertext.len() < OVERHEAD || ciphertext.get(..MAGIC.len()) != Some(MAGIC) {
            return Err(Error::Encryption);
        }
        let wrapper =
            KwAes256::new_from_slice(self.wrapping.as_ref()).map_err(|_| Error::Encryption)?;
        let mut key = Zeroizing::new([0; KEY_BYTES]);
        wrapper
            .unwrap_key(&ciphertext[MAGIC.len()..HEADER], key.as_mut())
            .map_err(|_| Error::Encryption)?;
        let cipher = Aes256Gcm::new_from_slice(key.as_ref()).map_err(|_| Error::Encryption)?;
        let mut aad = Vec::with_capacity(MAGIC.len() + context.len());
        aad.extend_from_slice(MAGIC);
        aad.extend_from_slice(context.as_bytes());
        let end = ciphertext.len() - TAG_BYTES;
        let tag = ciphertext[end..]
            .try_into()
            .map_err(|_| Error::Encryption)?;
        cipher
            .decrypt_inout_detached(
                &NONCE.into(),
                &aad,
                (&mut ciphertext[HEADER..end]).into(),
                &tag,
            )
            .map_err(|_| Error::Encryption)?;
        Ok(Bytes::from(ciphertext).slice(HEADER..end))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn records_authenticate_content_context_key_and_format() {
        let cipher = Cipher::new(EncryptionKey::from_bytes([1; 32]));
        let bytes = cipher
            .seal("objects/one", b"private content".to_vec())
            .unwrap();
        assert_eq!(
            cipher.open("objects/one", bytes.clone()).unwrap().as_ref(),
            b"private content"
        );
        assert!(cipher.open("objects/two", bytes.clone()).is_err());
        assert!(
            Cipher::new(EncryptionKey::from_bytes([2; 32]))
                .open("objects/one", bytes.clone())
                .is_err()
        );
        for offset in [0, MAGIC.len(), HEADER, bytes.len() - 1] {
            let mut changed = bytes.clone();
            changed[offset] ^= 1;
            assert!(cipher.open("objects/one", changed).is_err());
        }
        assert_ne!(
            cipher
                .seal("objects/one", b"private content".to_vec())
                .unwrap(),
            bytes
        );
        assert_ne!(cipher.name(&["a", "bc"]), cipher.name(&["ab", "c"]));
    }

    #[test]
    fn empty_plaintext_is_authenticated() {
        let cipher = Cipher::new(EncryptionKey::from_bytes([1; 32]));
        let sealed = cipher.seal("empty", Vec::new()).unwrap();
        assert!(cipher.open("empty", sealed.clone()).unwrap().is_empty());
        assert!(cipher.open("other", sealed.clone()).is_err());
        assert!(
            cipher
                .open("empty", sealed[..sealed.len() - 1].to_vec())
                .is_err()
        );
        for length in 0..OVERHEAD {
            assert!(cipher.open("empty", vec![0; length]).is_err());
        }
    }

    #[test]
    fn reads_an_independently_encoded_oct_jwk() {
        let directory = tempfile::tempdir().unwrap();
        let path = directory.path().join("key");
        EncryptionKey::generate(&path).unwrap();
        // RFC 7517 permits additional members and does not prescribe member order.
        std::fs::write(
            &path,
            br#"{"kid":"external-key","k":"AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8","kty":"oct"}"#,
        )
        .unwrap();
        let expected = Cipher::new(EncryptionKey::from_bytes(std::array::from_fn(|i| i as u8)));
        let loaded = Cipher::new(EncryptionKey::read(&path).unwrap());
        let sealed = expected.seal("interop", b"external key".to_vec()).unwrap();
        assert_eq!(
            loaded.open("interop", sealed).unwrap().as_ref(),
            b"external key"
        );
    }

    #[test]
    fn rejects_invalid_jwks_without_disclosing_key_material() {
        let directory = tempfile::tempdir().unwrap();
        let path = directory.path().join("key");
        EncryptionKey::generate(&path).unwrap();
        let valid = "AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8";
        let invalid = [
            serde_json::json!({"kty": "RSA", "k": valid}),
            serde_json::json!({"kty": 123, "k": valid}),
            serde_json::json!({"kty": "oct", "k": 123}),
            serde_json::json!({"kty": "oct"}),
            serde_json::json!({"k": valid}),
            serde_json::json!({"kty": "oct", "k": ""}),
            serde_json::json!({"kty": "oct", "k": URL_SAFE_NO_PAD.encode([0; 31])}),
            serde_json::json!({"kty": "oct", "k": URL_SAFE_NO_PAD.encode([0; 33])}),
            serde_json::json!({"kty": "oct", "k": format!("{valid}=")}),
            serde_json::json!({"kty": "oct", "k": format!("{valid} ")}),
            serde_json::json!({"kty": "oct", "k": "/".repeat(43)}),
            serde_json::json!({"kty": "oct", "k": "+".repeat(43)}),
            // A noncanonical final sextet must not silently discard trailing bits.
            serde_json::json!({"kty": "oct", "k": format!("{}9", &valid[..42])}),
            serde_json::json!({"kty": "oct", "k": "sensitive-key-material"}),
            serde_json::json!([{"kty": "oct", "k": valid}]),
        ];
        for jwk in invalid {
            std::fs::write(&path, serde_json::to_vec(&jwk).unwrap()).unwrap();
            let Err(error) = EncryptionKey::read(&path) else {
                panic!("invalid JWK accepted");
            };
            let message = error.to_string();
            assert!(!message.contains(valid));
            assert!(!message.contains("sensitive-key-material"));
        }
        for malformed in [
            vec![42; 32],
            b"{".to_vec(),
            format!(r#"{{"kty":"oct","k":"{valid}","k":"{valid}"}}"#).into_bytes(),
            format!(r#"{{"kty":"oct","k":"{valid}"}} trailing"#).into_bytes(),
        ] {
            std::fs::write(&path, malformed).unwrap();
            assert!(EncryptionKey::read(&path).is_err());
        }
    }

    #[cfg(unix)]
    #[test]
    fn key_files_are_owner_only_and_public_permissions_are_rejected() {
        use std::os::unix::fs::PermissionsExt;

        let directory = tempfile::tempdir().unwrap();
        let path = directory.path().join("key");
        EncryptionKey::generate(&path).unwrap();
        let mode = std::fs::metadata(&path).unwrap().permissions().mode();
        assert_eq!(mode & 0o077, 0);
        EncryptionKey::read(&path).unwrap();
        for mode in [0o640, 0o604, 0o660, 0o606] {
            std::fs::set_permissions(&path, std::fs::Permissions::from_mode(mode)).unwrap();
            assert!(EncryptionKey::read(&path).is_err());
        }
    }

    #[test]
    fn key_generation_never_replaces_a_backup() {
        let directory = tempfile::tempdir().unwrap();
        let path = directory.path().join("key");
        EncryptionKey::generate(&path).unwrap();
        let original = std::fs::read(&path).unwrap();
        assert!(EncryptionKey::generate(&path).is_err());
        assert_eq!(std::fs::read(&path).unwrap(), original);
        let jwk: serde_json::Value = serde_json::from_slice(&original).unwrap();
        assert!(original.is_ascii());
        assert_eq!(jwk["kty"], "oct");
        let encoded = jwk["k"].as_str().unwrap();
        assert_eq!(encoded.len(), 43);
        assert!(
            encoded
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-' || byte == b'_')
        );
        let decoded: [u8; 32] = URL_SAFE_NO_PAD.decode(encoded).unwrap().try_into().unwrap();
        let loaded = Cipher::new(EncryptionKey::read(&path).unwrap());
        let independent = Cipher::new(EncryptionKey::from_bytes(decoded));
        let sealed = independent.seal("generated", b"key file".to_vec()).unwrap();
        assert_eq!(
            loaded.open("generated", sealed).unwrap().as_ref(),
            b"key file"
        );
        let second_path = directory.path().join("second-key");
        EncryptionKey::generate(&second_path).unwrap();
        let second: serde_json::Value =
            serde_json::from_slice(&std::fs::read(second_path).unwrap()).unwrap();
        assert_ne!(jwk["k"], second["k"]);
    }
}
